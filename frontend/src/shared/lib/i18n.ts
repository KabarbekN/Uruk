export type Locale = 'en' | 'ru';
export type TranslationKey = Key;
function initialLocale(): Locale {
  try {
    return localStorage.getItem('sbm.locale') === 'ru' ? 'ru' : 'en';
  } catch {
    return 'en';
  }
}
export const useLocale = create<{
  locale: Locale;
  setLocale: (locale: Locale) => void;
}>((set) => ({
  locale: initialLocale(),
  setLocale: (locale) => {
    set({ locale });
    document.documentElement.lang = locale;
    try {
      localStorage.setItem('sbm.locale', locale);
    } catch {
      /* Storage is optional. */
    }
  },
}));
